#!/usr/bin/env python3
"""Generate per-ruleset appendices (tech tree, modifier matrix, glossary) from data/<ruleset>.yaml.

vendetta -> docs/spec/appendix/*.md ; space4k -> docs/spec/space4k/appendix/*.md
"""

from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs/spec"
RULESETS = {"vendetta": SPEC / "appendix", "space4k": SPEC / "space4k" / "appendix"}

GENERATED = "<!-- GENERATED by scripts/generate_spec_appendix.py from data/{ruleset}.yaml. Do not edit by hand. -->"


def fmt_reqs(reqs: dict) -> str:
    return ", ".join(f"`{k}` ≥ {v}" for k, v in reqs.items()) or "—"


def tech_tree(data: dict) -> str:
    lines = [
        GENERATED.format(ruleset=data["ruleset"]),
        f"# Technology Tree — {data['ruleset']}",
        "",
        "Building requirements refer to **room levels in the same building**. Research and troop",
        "requirements refer to the player's **research levels**.",
        "",
        "## Buildings",
        "",
        "| Building | Requires (rooms) |",
        "|----------|------------------|",
    ]
    lines += [f"| `{b['id']}` | {fmt_reqs(b['requirements'])} |" for b in data["buildings"]]
    lines += ["", "## Research", "", "| Research | Requires (research) |", "|----------|---------------------|"]
    lines += [f"| `{r['id']}` | {fmt_reqs(r['requirements'])} |" for r in data["research"]]
    lines += ["", "## Troops", "", "| Troop | Role | Requires (research) |", "|-------|------|---------------------|"]
    lines += [f"| `{t['id']}` | {t['role']} | {fmt_reqs(t['requirements'])} |" for t in data["troops"]]
    return "\n".join(lines) + "\n"


def modifier_matrix(data: dict) -> str:
    troops = data["troops"]
    lines = [
        GENERATED.format(ruleset=data["ruleset"]),
        f"# Combat Modifier Matrix — {data['ruleset']}",
        "",
        "Matchup multipliers used by the **Modificadores** engine (`Mob_Tropa_Abstract::getModificador`).",
        "",
        "When a stack of troop **X** fights a stack of enemy troop **Y**, both X's attack power and X's",
        "defense power in that pairwise fight are multiplied by `modifier[X][Y]` (default 1). The value is",
        "independent of which side (attacker/defender) X is on. Modifiers are **not symmetric**: Y uses",
        "its own `modifier[Y][X]`.",
        "",
        "## By troop",
        "",
        "| Troop X | Strong against (×>1) | Weak against (×<1) |",
        "|---------|----------------------|--------------------|",
    ]
    for t in troops:
        mods = t["combat_modifiers"]
        strong = ", ".join(f"`{k}` ×{v}" for k, v in mods.items() if v > 1) or "—"
        weak = ", ".join(f"`{k}` ×{v}" for k, v in mods.items() if v < 1) or "—"
        lines.append(f"| `{t['id']}` | {strong} | {weak} |")

    targets = [t["id"] for t in troops if any(t["id"] in o["combat_modifiers"] for o in troops)]
    lines += [
        "",
        "## Matrix",
        "",
        "Rows = X (the stack whose power is multiplied), columns = Y (the enemy type). Only columns that",
        "appear in at least one modifier are shown; empty cell = 1.",
        "",
        "| X \\ Y | " + " | ".join(f"`{i}`" for i in targets) + " |",
        "|---|" + "|".join(["---"] * len(targets)) + "|",
    ]
    for t in troops:
        cells = [str(t["combat_modifiers"].get(y, "")) for y in targets]
        lines.append(f"| `{t['id']}` | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def glossary(data: dict) -> str:
    lines = [
        GENERATED.format(ruleset=data["ruleset"]),
        f"# Glossary: legacy IDs ↔ spec IDs — {data['ruleset']}",
        "",
        "The legacy database columns, battle-report JSON and PHP class names use Spanish IDs.",
        "IDs must always be resolved per kind: in Vendetta `contrabando` and `seguridad` are **both** a room and a research.",
        "",
        "## Resources",
        "",
        "| Spec ID | Legacy column suffix |",
        "|---------|----------------------|",
    ]
    legacy_cols = {"weapons": "arm", "ammunition": "mun", "alcohol": "alc", "dollar": "dol",
                   "iron": "arm", "lutinum": "mun", "water": "alc", "hydrogen": "dol"}
    lines += [f"| `{r}` | `{legacy_cols[r]}` |" for r in data["resources"]]
    for section, title in (("buildings", "Buildings (rooms)"), ("research", "Research"), ("troops", "Troops")):
        lines += ["", f"## {title}", "", "| Spec ID | Legacy ID | English name |", "|---------|-----------|--------------|"]
        lines += [f"| `{e['id']}` | `{e['legacy_id']}` | {e['name']} |" for e in data[section]]
    lines += [
        "",
        "## Other legacy terms",
        "",
        "| Legacy | Meaning |",
        "|--------|---------|",
        "| `edificio` | Map building (a coordinate the player owns) |",
        "| `habitacion` | Room (what this spec calls a building type) |",
        "| `entrenamiento` | Research |",
        "| `tropa` | Troop |",
        "| `mision` | Mission |",
        "| `batalla` | Battle report |",
        "| `familia` | Family (alliance) |",
        "| `guerra` | War between families |",
        "| `mercado` | Market |",
        "| `coord1` / `coord2` / `coord3` | City / neighborhood / slot |",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    for ruleset, out in RULESETS.items():
        data = yaml.safe_load((SPEC / "data" / f"{ruleset}.yaml").read_text(encoding="utf-8"))
        out.mkdir(parents=True, exist_ok=True)
        (out / "tech-tree.md").write_text(tech_tree(data), encoding="utf-8")
        (out / "modifier-matrix.md").write_text(modifier_matrix(data), encoding="utf-8")
        (out / "glossary.md").write_text(glossary(data), encoding="utf-8")
        print(f"Wrote {out.relative_to(ROOT)}/{{tech-tree,modifier-matrix,glossary}}.md")

if __name__ == "__main__":
    main()
