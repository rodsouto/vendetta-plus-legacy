#!/usr/bin/env python3
"""Generate the entity chapters of each ruleset from data/<ruleset>.yaml.

vendetta -> docs/spec/02-buildings.md, 03-research.md, 04-troops.md
space4k  -> docs/spec/space4k/02-buildings.md, 03-research.md, 04-troops.md
"""

from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs/spec"
RULESETS = {"vendetta": SPEC, "space4k": SPEC / "space4k"}


class Writer:
    def __init__(self, ruleset: str, data: dict, out: Path):
        self.ruleset = ruleset
        self.data = data
        self.roles = data["roles"]
        self.out = out
        # Relative prefix from the output dir to docs/spec
        self.up = "" if out == SPEC else "../"

    def header(self) -> list[str]:
        return [f"<!-- GENERATED by scripts/generate_entity_docs.py from data/{self.ruleset}.yaml. "
                "Do not edit by hand. -->"]

    def link(self, path: str) -> str:
        return f"{self.up}{path}"

    def write(self, name: str, lines: list[str]) -> None:
        self.out.mkdir(parents=True, exist_ok=True)
        (self.out / name).write_text("\n".join(lines), encoding="utf-8")

    @staticmethod
    def costs(cost: dict) -> str:
        return ", ".join(f"{v:,} {k}" for k, v in cost.items()) or "—"

    @staticmethod
    def reqs(reqs: dict) -> str:
        return ", ".join(f"`{k}` ≥ {v}" for k, v in reqs.items()) or "—"

    @staticmethod
    def ids(ids: list) -> str:
        return ", ".join(f"`{i}`" for i in ids) or "—"

    @staticmethod
    def num(v) -> str:
        return "—" if v is None else f"{v:,}"

    @staticmethod
    def quote(text: str) -> list[str]:
        return [f"> {text}", ""] if text else []

    def role_rows(self, entity_id: str) -> list[str]:
        return [f"| Engine role | `{role}` |" for role, rid in self.roles.items() if rid == entity_id]

    def buildings(self) -> None:
        r = self.roles
        lines = self.header() + [
            f"# Buildings (rooms) — {self.ruleset}",
            "",
            f"Each owned map building (`city:neighborhood:slot`) has its own level for each of these "
            f"{len(self.data['buildings'])} rooms.",
            f"Formulas: [05-formulas.md]({self.link('05-formulas.md')}). Upgrade time is divided by the "
            f"`{r['build_speed_room']}` level of the same building and by `upgrade_speed_multiplier` "
            f"([game_config.yaml]({self.link('data/game_config.yaml')})).",
            "",
            "| Room | Base cost | Base duration | Points/level | Requires |",
            "|------|-----------|---------------|--------------|----------|",
        ]
        for e in self.data["buildings"]:
            lines.append(f"| [{e['name']}](#{e['id']}) | {self.costs(e['cost'])} | {e['base_duration_s']:,} s | "
                         f"{e['points_per_level']} | {self.reqs(e['requirements'])} |")
        lines.append("")
        # Rooms with no production, storage or engine role do nothing in legacy (D-09).
        no_effect = {b["id"] for b in self.data["buildings"]
                     if "production" not in b and "storage" not in b and b["id"] not in r.values()}
        for e in self.data["buildings"]:
            lines += [f"## {e['id']}", "", f"**{e['name']}** (legacy `{e['legacy_id']}`)", ""]
            lines += self.quote(e["description"])
            lines += [
                "| Stat | Value |",
                "|------|-------|",
                f"| Base upgrade cost | {self.costs(e['cost'])} |",
                f"| Base duration | {e['base_duration_s']:,} s |",
                f"| Points per level | {e['points_per_level']} |",
                f"| Requirements | {self.reqs(e['requirements'])} |",
            ] + self.role_rows(e["id"])
            if p := e.get("production"):
                lines.append(f"| Produces | `{p['resource']}` per hour: `{p['formula']}` |")
                if p["kind"] == "converter":
                    lines.append(f"| Consumes | `{p['consumes']}` "
                                 f"(see [01-resources.md]({self.link('01-resources.md')}#alcohol--dollar)) |")
            if s := e.get("storage"):
                lines.append(f"| Stores / protects | `{s['resource']}`: `{s['formula']}` |")
            if e["id"] in no_effect:
                lines.append(f"| Gameplay effect | **None in legacy** — only grants points. "
                             f"See [D-09]({self.link('decisions.md')}#d-09--spring-gun--hidden-mines--keep). |")
            lines.append("")
        self.write("02-buildings.md", lines)

    def research(self) -> None:
        lines = self.header() + [
            f"# Research — {self.ruleset}",
            "",
            "Research levels belong to the **player** (shared by all their buildings), but each upgrade is queued in, "
            f"paid from and timed by one building's `{self.roles['research_speed_room']}`. "
            f"Formulas: [05-formulas.md]({self.link('05-formulas.md')}).",
            "",
            "| Research | Base cost | Base duration | Points/level | Requires |",
            "|----------|-----------|---------------|--------------|----------|",
        ]
        for e in self.data["research"]:
            lines.append(f"| [{e['name']}](#{e['id']}) | {self.costs(e['cost'])} | {e['base_duration_s']:,} s | "
                         f"{e['points_per_level']} | {self.reqs(e['requirements'])} |")
        lines.append("")
        for e in self.data["research"]:
            lines += [f"## {e['id']}", "", f"**{e['name']}** (legacy `{e['legacy_id']}`)", ""]
            lines += self.quote(e["description"])
            lines += [
                "| Stat | Value |",
                "|------|-------|",
                f"| Base upgrade cost | {self.costs(e['cost'])} |",
                f"| Base duration | {e['base_duration_s']:,} s |",
                f"| Points per level | {e['points_per_level']} |",
                f"| Requirements | {self.reqs(e['requirements'])} |",
            ] + self.role_rows(e["id"]) + [""]
        self.write("03-research.md", lines)

    def troops(self) -> None:
        troops = self.data["troops"]
        n_att = sum(t["role"] == "attack" for t in troops)
        mult = self.data["rules"]["troop_defense_multiplier"]
        lines = self.header() + [
            f"# Troops — {self.ruleset}",
            "",
            f"{len(troops)} troop types: {n_att} attack (trained at `{self.roles['attack_training_room']}`) + "
            f"{len(troops) - n_att} defense (trained at `{self.roles['defense_training_room']}`).",
            "Only attack troops can be sent on missions; defense troops never leave their building.",
            "Order below is the canonical troop order (used for deterministic iteration in combat).",
            "",
            f"**`base_defense` is the raw class value.** In this ruleset `troop_defense_multiplier` = **{mult}**: "
            f"every troop's effective defense starts from `base_defense × {mult}` "
            f"([05-formulas.md]({self.link('05-formulas.md')}#troop-effective-stats)).",
            "",
            "| Troop | Role | Cost/unit | Time | Pts | Atk | Def (raw) | Cap | Speed | Salary |",
            "|-------|------|-----------|------|-----|-----|-----------|-----|-------|--------|",
        ]
        for e in troops:
            lines.append(
                f"| [{e['name']}](#{e['id']}) | {e['role']} | {self.costs(e['cost'])} | "
                f"{e['training_duration_s']:,} s | {e['points_per_unit']} | {e['base_attack']} | {e['base_defense']} | "
                f"{self.num(e['base_capacity'])} | {self.num(e['base_speed'])} | {self.num(e['salary'])} |")
        lines.append("")
        for e in troops:
            mods = ", ".join(f"vs `{k}` ×{v}" for k, v in e["combat_modifiers"].items()) or "—"
            lines += [f"## {e['id']}", "", f"**{e['name']}** (legacy `{e['legacy_id']}`) — {e['role']}", ""]
            lines += self.quote(e["description"])
            lines += [
                "| Stat | Value |",
                "|------|-------|",
                f"| Trained at | `{e['trained_at']}` |",
                f"| Training cost (per unit) | {self.costs(e['cost'])} |",
                f"| Training duration (per unit, level 1) | {e['training_duration_s']:,} s |",
                f"| Points per unit | {e['points_per_unit']} |",
                f"| Base attack / defense (raw) | {e['base_attack']} / {e['base_defense']} |",
            ]
            if e["role"] == "attack":
                lines += [
                    f"| Base capacity / speed | {self.num(e['base_capacity'])} / {self.num(e['base_speed'])} |",
                    f"| Salary per unit | {e['salary']} |",
                    f"| Speed research | `{e['speed_research']}` |",
                ]
            lines += [
                f"| Requirements | {self.reqs(e['requirements'])} |",
                f"| Attack bonuses from | {self.ids(e['attack_research_bonuses'])} |",
                f"| Defense bonuses from | {self.ids(e['defense_research_bonuses'])} |",
                f"| Combat modifiers | {mods} |",
            ] + self.role_rows(e["id"])
            for note in e.get("legacy_notes", []):
                lines.append(f"| Legacy note | {note} |")
            lines.append("")
        self.write("04-troops.md", lines)


def main() -> None:
    for ruleset, out in RULESETS.items():
        data = yaml.safe_load((SPEC / "data" / f"{ruleset}.yaml").read_text(encoding="utf-8"))
        w = Writer(ruleset, data, out)
        w.buildings()
        w.research()
        w.troops()
        print(f"Wrote {out.relative_to(ROOT)}/{{02-buildings,03-research,04-troops}}.md")


if __name__ == "__main__":
    main()
