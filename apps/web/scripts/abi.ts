// Exports the Game ABI for the client: Game's own functions and events plus the custom errors of
// the linked libraries (they revert inside Game, so the client must be able to decode them).
// Reads contracts/out (run `forge build` first). Output: src/chain/abi.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../../contracts/out");
const artifact = (file: string, name: string) =>
  JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8")).abi as {
    type: string;
    name?: string;
  }[];

const abi = artifact("Game.sol", "Game");
const seen = new Set(abi.map((e) => `${e.type}:${e.name ?? ""}`));
for (const [file, name] of [
  ["GameErrors.sol", "IGameEvents"],
  ["Core.sol", "Core"],
  ["Training.sol", "Training"],
  ["Missions.sol", "Missions"],
  ["Battle.sol", "Battle"],
  ["Account.sol", "Account"],
  ["Families.sol", "Families"],
  ["Market.sol", "Market"],
  ["Settlement.sol", "SettleLib"],
]) {
  for (const entry of artifact(file!, name!)) {
    if (entry.type !== "error" && entry.type !== "event") continue;
    const key = `${entry.type}:${entry.name}`;
    if (seen.has(key)) continue;
    seen.add(key);
    abi.push(entry);
  }
}
const dest = join(here, "../src/chain/abi.ts");
writeFileSync(
  dest,
  `// GENERATED by apps/web/scripts/abi.ts from contracts/out. DO NOT EDIT: run \`pnpm codegen\`.\nexport const gameAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`apps/web/src/chain/abi.ts: ${abi.length} entries`);
