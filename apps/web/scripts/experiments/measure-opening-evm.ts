// Local EVM benchmark of the generated pairing-component verifier, never the game.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { encodeFunctionData } from "viem";
import { sha256Hex } from "./opening.js";

const work = resolve(process.argv[2] ?? "/tmp/vendetta-opening-tools/proof-run");
const metrics = JSON.parse(readFileSync(join(work, "metrics.json"), "utf8")) as {
  publicInputs: number;
  scope?: string;
};
const artifact = JSON.parse(readFileSync(join(work, "proof.json"), "utf8")) as {
  proof: `0x${string}`;
  publicInputs: string[];
};
const n = metrics.publicInputs;
const callGasBudget = Number(process.env.COMPONENT_GAS_BUDGET ?? 2000000);
if (!Number.isSafeInteger(callGasBudget) || callGasBudget < 1)
  throw new Error("Invalid gas budget");
const hasInvalidCertificate = existsSync(join(work, "invalid-proof.json"));
if (artifact.publicInputs.length !== n) throw new Error("Witness length does not match circuit");
mkdirSync(join(work, "src"), { recursive: true });
mkdirSync(join(work, "test"), { recursive: true });
copyFileSync(join(work, "PairingVerifier.sol"), join(work, "src/PairingVerifier.sol"));
writeFileSync(
  join(work, "foundry.toml"),
  `[profile.default]\nsrc = "src"\ntest = "test"\nsolc_version = "0.8.28"\nevm_version = "cancun"\noptimizer = true\noptimizer_runs = 200\nfs_permissions = [{ access = "read", path = "./proof.json" }${hasInvalidCertificate ? ', { access = "read", path = "./invalid-proof.json" }' : ""}]\n`,
);
writeFileSync(
  join(work, "test/Pairing.t.sol"),
  `// Benchmark-only verifier generated by a fresh local trusted setup.
pragma solidity 0.8.28;
import {Verifier} from "../src/PairingVerifier.sol";
interface Vm {
  function readFile(string calldata) external view returns(string memory);
  function parseJsonBytes(string calldata,string calldata) external pure returns(bytes memory);
  function parseJsonStringArray(string calldata,string calldata) external pure returns(string[] memory);
  function parseUint(string calldata) external pure returns(uint256);
}
contract PairingComponentTest {
  Vm constant vm = Vm(address(uint160(uint256(keccak256("hevm cheat code")))));
  Verifier verifier;
  event log_named_uint(string key, uint256 val);
  function setUp() public {verifier=new Verifier();}
  function inputs() internal view returns(bytes memory proof,uint256[${n}] memory values) {
    return loadInputs("proof.json");
  }
  function loadInputs(string memory path) internal view returns(bytes memory proof,uint256[${n}] memory values) {
    string memory data=vm.readFile(path);
    proof=vm.parseJsonBytes(data,".proof");
    string[] memory strings=vm.parseJsonStringArray(data,".publicInputs");
    require(strings.length==${n});
    for(uint256 i;i<${n};i++) values[i]=vm.parseUint(strings[i]);
  }
  function test_valid_component() public {
    (bytes memory proof,uint256[${n}] memory values)=inputs();
    uint256 beforeGas=gasleft();
    verifier.verifyProof(proof,values);
    emit log_named_uint("component_verify_gas",beforeGas-gasleft());
  }
  function test_reject_changed_public_input() public {
    (bytes memory proof,uint256[${n}] memory values)=inputs();
    values[${n - 1}]^=1;
    uint256 beforeGas=gasleft();
    (bool ok,)=address(verifier).staticcall{gas:${callGasBudget}}(abi.encodeCall(verifier.verifyProof,(proof,values)));
    emit log_named_uint("component_bad_input_gas",beforeGas-gasleft());
    require(!ok,"tampered public input accepted");
  }
  function test_reject_changed_proof() public {
    (bytes memory proof,uint256[${n}] memory values)=inputs();
    proof[0]=bytes1(uint8(proof[0])^1);
    uint256 beforeGas=gasleft();
    (bool ok,)=address(verifier).staticcall{gas:${callGasBudget}}(abi.encodeCall(verifier.verifyProof,(proof,values)));
    emit log_named_uint("component_bad_proof_gas",beforeGas-gasleft());
    require(!ok,"tampered proof accepted");
  }
  function test_valid_under_call_gas_budget() public {
    (bytes memory proof,uint256[${n}] memory values)=inputs();
    (bool ok,)=address(verifier).staticcall{gas:${callGasBudget}}(abi.encodeCall(verifier.verifyProof,(proof,values)));
    require(ok,"valid proof failed under the component call budget");
  }
  ${
    hasInvalidCertificate
      ? `
  function test_valid_invalid_capsule_certificate() public {
    (bytes memory proof,uint256[${n}] memory values)=loadInputs("invalid-proof.json");
    require(values[${n - 1}]==0,"expected invalid capsule result");
    uint256 beforeGas=gasleft();
    (bool ok,)=address(verifier).staticcall{gas:${callGasBudget}}(abi.encodeCall(verifier.verifyProof,(proof,values)));
    emit log_named_uint("component_invalid_certificate_gas",beforeGas-gasleft());
    require(ok,"invalid capsule certificate rejected");
  }
  function test_cannot_flip_invalid_capsule_to_valid() public {
    (bytes memory proof,uint256[${n}] memory values)=loadInputs("invalid-proof.json");
    values[${n - 1}]=1;
    (bool ok,)=address(verifier).staticcall{gas:${callGasBudget}}(abi.encodeCall(verifier.verifyProof,(proof,values)));
    require(!ok,"forged capsule result accepted");
  }
  `
      : ""
  }
}
`,
);
const forge = process.env.FORGE_BIN ?? join(homedir(), ".foundry/bin/forge");
const compiler = process.env.SOLC_BIN ? ["--use", process.env.SOLC_BIN] : [];
const output = process.argv[3]
  ? resolve(process.argv[3])
  : fileURLToPath(new URL("../../../../docs/benchmarks/timelock-opening/", import.meta.url));
const archive = (report: object) => {
  mkdirSync(output, { recursive: true });
  writeFileSync(join(output, "evm-results.json"), JSON.stringify(report, null, 2) + "\n");
  copyFileSync(join(work, "metrics.json"), join(output, "pairing-proof-results.json"));
  copyFileSync(join(work, "PairingVerifier.sol"), join(output, "PairingVerifier.sol"));
  copyFileSync(join(work, "proof.json"), join(output, "pairing-proof.json"));
  if (hasInvalidCertificate)
    copyFileSync(join(work, "invalid-proof.json"), join(output, "invalid-proof.json"));
};
const built = spawnSync(forge, ["build", "--root", work, ...compiler], {
  cwd: work,
  encoding: "utf8",
  timeout: 300000,
});
if (built.status !== 0) throw new Error(built.stderr || String(built.error));
const compiled = JSON.parse(
  readFileSync(join(work, "out/PairingVerifier.sol/Verifier.json"), "utf8"),
) as { deployedBytecode: { object: string } };
const bytecode = compiled.deployedBytecode.object.replace(/^0x/, "");
const deployedBytecodeBytes = bytecode.length / 2;
if (deployedBytecodeBytes > 24576) {
  const report = {
    componentOnly: true,
    scope: metrics.scope,
    evm: "cancun",
    solc: "0.8.28",
    deployedBytecodeBytes,
    eip170LimitBytes: 24576,
    standardDeploymentPossible: false,
    deploymentAttempted: false,
    measuredVerifierCallGas: null,
    positiveAndTamperTestsPassed: 0,
    reason: "Generated verifier exceeds EIP-170; code size limits were not relaxed",
    publicInputs: n,
    proofBytes: (artifact.proof.length - 2) / 2,
    verifierSha256: sha256Hex(readFileSync(join(work, "PairingVerifier.sol"))),
    proofJsonSha256: sha256Hex(readFileSync(join(work, "proof.json"))),
  };
  archive(report);
  console.log(JSON.stringify(report));
  process.exit(0);
}
const result = spawnSync(forge, ["test", "--root", work, ...compiler, "-vv"], {
  cwd: work,
  encoding: "utf8",
  timeout: 300000,
});
console.log(result.stdout);
if (result.status !== 0) throw new Error(result.stderr || String(result.error));
const gas = Number(result.stdout.match(/component_verify_gas:\s*(\d+)/)?.[1]);
if (!Number.isFinite(gas)) throw new Error("Missing measured gas");
const badInputGas = Number(result.stdout.match(/component_bad_input_gas:\s*(\d+)/)?.[1]);
const badProofGas = Number(result.stdout.match(/component_bad_proof_gas:\s*(\d+)/)?.[1]);
if (!Number.isFinite(badInputGas) || !Number.isFinite(badProofGas))
  throw new Error("Missing rejection gas");
const calldata = encodeFunctionData({
  abi: [
    {
      type: "function",
      name: "verifyProof",
      stateMutability: "view",
      inputs: [
        { name: "proof", type: "bytes" },
        { name: "inputs", type: `uint256[${n}]` },
      ],
      outputs: [],
    },
  ],
  functionName: "verifyProof",
  args: [artifact.proof, artifact.publicInputs.map(BigInt)],
});
const report = {
  componentOnly: true,
  deployedBytecodeBytes,
  eip170LimitBytes: 24576,
  standardDeploymentPossible: true,
  scope: metrics.scope,
  evm: "cancun",
  solc: "0.8.28",
  measuredVerifierCallGas: gas,
  calldataBytes: (calldata.length - 2) / 2,
  proofBytes: (artifact.proof.length - 2) / 2,
  positiveAndTamperTestsPassed: hasInvalidCertificate ? 6 : 4,
  componentVerifierCallGasBudget: callGasBudget,
  badPublicInputCallGas: badInputGas,
  badProofCallGas: badProofGas,
  transactionGasOrGnosisDeploymentMeasured: false,
  verifierSha256: sha256Hex(readFileSync(join(work, "PairingVerifier.sol"))),
  proofJsonSha256: sha256Hex(readFileSync(join(work, "proof.json"))),
  testHarnessSha256: sha256Hex(readFileSync(join(work, "test/Pairing.t.sol"))),
};
if (hasInvalidCertificate) {
  Object.assign(report, {
    invalidCapsuleCertificateCallGas: Number(
      result.stdout.match(/component_invalid_certificate_gas:\s*(\d+)/)?.[1],
    ),
  });
}
archive(report);
console.log(JSON.stringify(report));
